from torch.utils.data import Dataset

class FastGCPDataset(Dataset):

    def __init__(self, files):

        self.files = files

    def __len__(self):
        return len(self.files)

    def __getitem__(self, idx):

        data = np.load(
            self.files[idx]
        )

        image = data["image"]
        target = data["target"]

        image = image.astype(np.float32) / 255.0

        image = (
            image -
            np.array([0.485,0.456,0.406])
        ) / np.array(
            [0.229,0.224,0.225]
        )

        image = torch.tensor(
            image.transpose(2,0,1),
            dtype=torch.float32
        )

        target = torch.tensor(
            target,
            dtype=torch.float32
        )

        return image, target

