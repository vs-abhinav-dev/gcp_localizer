import random

PREPROCESSED_DIR = "/content/preprocessed"

os.makedirs(PREPROCESSED_DIR, exist_ok=True)

CROP_SIZE = 512
OUTPUT_SIZE = 224

sample_idx = 0

for rel_path, info in tqdm(annotations.items()):

    img_path = os.path.join(
        "/content/dataset/train_dataset",
        rel_path
    )

    image = cv2.imread(img_path)

    if image is None:
        print("Skipping:", img_path)
        continue

    image = cv2.cvtColor(
        image,
        cv2.COLOR_BGR2RGB
    )

    h, w = image.shape[:2]

    cx = float(info["mark"]["x"])
    cy = float(info["mark"]["y"])

    for aug in range(5):

        dx = random.randint(-128, 128)
        dy = random.randint(-128, 128)

        crop_center_x = cx + dx
        crop_center_y = cy + dy

        half = CROP_SIZE // 2

        x1 = int(crop_center_x - half)
        y1 = int(crop_center_y - half)

        x2 = x1 + CROP_SIZE
        y2 = y1 + CROP_SIZE

        pad_left = max(0, -x1)
        pad_top = max(0, -y1)

        pad_right = max(0, x2 - w)
        pad_bottom = max(0, y2 - h)

        padded = cv2.copyMakeBorder(
            image,
            pad_top,
            pad_bottom,
            pad_left,
            pad_right,
            cv2.BORDER_CONSTANT
        )

        x1 += pad_left
        x2 += pad_left

        y1 += pad_top
        y2 += pad_top

        crop = padded[y1:y2, x1:x2]

        rel_x = cx - (crop_center_x - half)
        rel_y = cy - (crop_center_y - half)

        scale = OUTPUT_SIZE / CROP_SIZE

        rel_x *= scale
        rel_y *= scale

        crop = cv2.resize(
            crop,
            (OUTPUT_SIZE, OUTPUT_SIZE)
        )

        save_path = os.path.join(
            PREPROCESSED_DIR,
            f"{sample_idx}.npz"
        )

        np.savez_compressed(
        save_path,
        image=crop,
        target=np.array(
            [rel_x, rel_y],
            dtype=np.float32
        ),
        path=rel_path,
        original_center=np.array(
            [cx, cy],
            dtype=np.float32
        ),
        offset=np.array(
            [dx, dy],
            dtype=np.int32
        ),
        shape=info.get("verified_shape", "Unknown"),
        label=1
      )

        sample_idx += 1

