import cv2
import numpy as np

mean = np.array(
    [0.485,0.456,0.406]
)

std = np.array(
    [0.229,0.224,0.225]
)

def preprocess_tile(tile):

    tile = cv2.resize(
        tile,
        (224,224)
    )

    tile = tile.astype(
        np.float32
    ) / 255.0

    tile = (
        tile - mean
    ) / std

    tile = torch.tensor(
        tile.transpose(2,0,1),
        dtype=torch.float32
    )

    return tile.unsqueeze(0)

shape_names = [
    "L-Shape",
    "Square",
    "Cross"
]

def predict_shape(tile):

    inp = preprocess_tile(
        tile
    ).to(device)

    with torch.no_grad():

        logits = shape_model(
            inp
        )

        pred = logits.argmax(
            dim=1
        ).item()

    return shape_names[pred]

def generate_tiles(
    image,
    tile_size=512,
    stride=128
):

    h, w = image.shape[:2]

    for y in range(
        0,
        h - tile_size + 1,
        stride
    ):

        for x in range(
            0,
            w - tile_size + 1,
            stride
        ):

            tile = image[
                y:y+tile_size,
                x:x+tile_size
            ]

            yield tile, x, y

def find_best_tile(image):

    best_prob = -1

    best_tile = None
    best_x = None
    best_y = None

    with torch.no_grad():

        for tile, x, y in generate_tiles(image):

            inp = preprocess_tile(
                tile
            ).to(device)

            logits = classifier(
                inp
            )

            probs = torch.softmax(
                logits,
                dim=1
            )

            marker_prob = (
                probs[0,1]
                .item()
            )

            if marker_prob > best_prob:

                best_prob = marker_prob

                best_tile = tile

                best_x = x
                best_y = y

    return (
        best_tile,
        best_x,
        best_y,
        best_prob
    )

def localize_marker(tile):

    inp = preprocess_tile(
        tile
    ).to(device)

    with torch.no_grad():

        pred = localizer(
            inp
        )[0]

    x = pred[0].item()
    y = pred[1].item()

    scale = 512 / 224

    x *= scale
    y *= scale

    return x, y

def localize_candidate(
    tile,
    tile_x,
    tile_y
):

    local_x, local_y = (
        localize_marker(tile)
    )

    return (
        tile_x + local_x,
        tile_y + local_y
    )

def predict_gcp(image):

    tile, tile_x, tile_y, prob = (
        find_best_tile(image)
    )

    shape = predict_shape(
        tile
    )

    local_x, local_y = (
        localize_marker(tile)
    )

    global_x = (
        tile_x + local_x
    )

    global_y = (
        tile_y + local_y
    )

    return {
    "x": global_x,
    "y": global_y,
    "shape": shape,
    "confidence": prob,
    "tile": tile
}

